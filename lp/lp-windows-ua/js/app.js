/* ============ 5. COUNTDOWN ============ */
function initCountdown(){
  function target(){
    var now = new Date(), d = new Date(now);
    var add = (7 - now.getDay()) % 7;
    d.setDate(now.getDate() + add); d.setHours(23,59,59,999);
    if (d <= now) d.setDate(d.getDate() + 7);
    return d;
  }
  var end = target();
  var pad = function(n){ return (n < 10 ? '0' : '') + n; };
  setInterval(function(){
    var diff = end - new Date();
    if (diff <= 0){ end = target(); diff = end - new Date(); }
    var s = Math.floor(diff / 1000);
    $('#cdD').textContent = pad(Math.floor(s / 86400));
    $('#cdH').textContent = pad(Math.floor(s / 3600) % 24);
    $('#cdM').textContent = pad(Math.floor(s / 60) % 60);
    $('#cdS').textContent = pad(s % 60);
  }, 1000);
}

