function initReviews(){
  var vp = $('#revViewport'), track = $('#revTrack'), cards = $$('.review-card', track);
  var dotsBox = $('#revDots'), index = 0, gap = 20, timer = null;
  function perView(){ var w = window.innerWidth; return w < 760 ? 1 : (w < 1080 ? 2 : 3); }
  function maxIndex(){ return Math.max(0, cards.length - perView()); }
  function buildDots(){
    dotsBox.innerHTML = '';
    for (var i = 0; i <= maxIndex(); i++){
      var d = document.createElement('button');
      d.className = 'rev-dot' + (i === index ? ' active' : '');
      d.setAttribute('aria-label', '• ' + (i + 1));
      (function(n){ d.addEventListener('click', function(){ go(n); restart(); }); })(i);
      dotsBox.appendChild(d);
    }
  }
  function go(i, instant){
    index = Math.max(0, Math.min(i, maxIndex()));
    var shift = index * (cards[0].offsetWidth + gap);
    if (instant) track.style.transition = 'none';
    track.style.transform = 'translateX(-' + shift + 'px)';
    if (instant){ void track.offsetWidth; track.style.transition = ''; }
    $('#revPrev').disabled = index === 0;
    $('#revNext').disabled = index >= maxIndex();
    $$('.rev-dot', dotsBox).forEach(function(d, n){ d.classList.toggle('active', n === index); });
  }
  function layout(){
    var pv = perView();
    cards.forEach(function(c){ c.style.flex = '0 0 calc((100% - ' + (pv - 1) * gap + 'px) / ' + pv + ')'; });
    if (index > maxIndex()) index = maxIndex();
    buildDots(); go(index, true);
  }
  function restart(){ clearInterval(timer); timer = setInterval(function(){ go(index >= maxIndex() ? 0 : index + 1); }, 6500); }
  $('#revPrev').addEventListener('click', function(){ go(index - 1); restart(); });
  $('#revNext').addEventListener('click', function(){ go(index + 1); restart(); });
  var startX = null, dx = 0;
  vp.addEventListener('pointerdown', function(e){ startX = e.clientX; dx = 0; vp.classList.add('dragging'); });
  vp.addEventListener('pointermove', function(e){ if (startX !== null) dx = e.clientX - startX; });
  function endDrag(){
    if (startX === null) return;
    if (Math.abs(dx) > 50) go(index + (dx < 0 ? 1 : -1));
    startX = null; vp.classList.remove('dragging'); restart();
  }
  vp.addEventListener('pointerup', endDrag);
  vp.addEventListener('pointerleave', endDrag);
  vp.addEventListener('mouseenter', function(){ clearInterval(timer); });
  vp.addEventListener('mouseleave', restart);
  window.addEventListener('resize', layout);
  layout(); restart();
}

