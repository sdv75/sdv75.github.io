var PRICING = {
  profilePerM2: { basic: 4200, comfort: 5800, premium: 8200 },   /* грн/м² */
  glassK:       { standard: 1.00, energy: 1.12, noise: 1.20, multi: 1.30 },
  objectK:      { flat: 1.00, house: 1.07, balcony: 0.90, loggia: 0.94 },
  constrK:      { single: 0.90, double: 1.00, triple: 1.10, block: 1.18, pano: 1.35 },
  constrFixed:  { single: 0, double: 0, triple: 600, block: 1700, pano: 2800 },
  minWindow: 3500,
  meshPerWindow: 900,
  sillBase: 1200, sillPerM: 500,
  slopesBase: 1400, slopesPerM: 300,
  demoPerWindow: 1100,
  deliveryFee: 2500, deliveryFreeFrom: 3,
  mountPerM2: 1000
};
var calcState = { object:'flat', count:3, width:1400, height:1400, constr:'double', profile:'comfort', glass:'energy',
                  opts:{ mesh:false, sill:true, slopes:true, demo:false, delivery:true, mount:true } };
var currentStep = 1;

function calcPrice(){
  var P = PRICING, s = calcState;
  var area = (s.width * s.height) / 1e6;
  var perWindow = Math.max(P.minWindow, area * P.profilePerM2[s.profile] * P.glassK[s.glass] * P.objectK[s.object] * P.constrK[s.constr]) + P.constrFixed[s.constr];
  var constructs = perWindow * s.count;
  var optsCost = 0, optsCount = 0;
  if (s.opts.mesh){   optsCost += P.meshPerWindow * s.count; optsCount++; }
  if (s.opts.sill){   optsCost += (P.sillBase + P.sillPerM * (s.width/1000)) * s.count; optsCount++; }
  if (s.opts.slopes){ optsCost += (P.slopesBase + P.slopesPerM * (2*(s.width+s.height)/1000)) * s.count; optsCount++; }
  if (s.opts.demo){   optsCost += P.demoPerWindow * s.count; optsCount++; }
  if (s.opts.delivery){ if (s.count < P.deliveryFreeFrom) optsCost += P.deliveryFee; optsCount++; }
  if (s.opts.mount){  optsCost += Math.round(P.mountPerM2 * area) * s.count; optsCount++; }
  return { area: area, perWindow: perWindow, constructs: constructs, optsCost: optsCost, optsCount: optsCount,
           total: Math.round((constructs + optsCost) / 10) * 10 };
}
function animateNumber(el, to){
  var from = parseFloat(el.dataset.val || '0'), dur = 550, t0 = null;
  el.dataset.val = to;
  function tick(ts){
    if (!t0) t0 = ts;
    var p = Math.min((ts - t0) / dur, 1), e = 1 - Math.pow(1 - p, 3);
    el.textContent = fmt(from + (to - from) * e);
    if (p < 1) requestAnimationFrame(tick);
  }
  requestAnimationFrame(tick);
}
