function validateField(input){
  var type = input.dataset.validate, ok = true;
  if (type === 'name') ok = input.value.trim().length >= 2;
  if (type === 'phone') ok = input.value.replace(/\D/g, '').length === 12; /* 380 + 9 цифр */
  input.closest('.form-field').classList.toggle('invalid', !ok);
  return ok;
}
function initForms(){
  $$('form[data-form]').forEach(function(form){
    var btn = $('button[type=submit]', form);
    btn.dataset.label = btn.textContent;
    $$('input[data-validate]', form).forEach(function(inp){
      if (inp.dataset.validate === 'phone') maskPhone(inp);
      inp.addEventListener('blur', function(){ if (inp.value) validateField(inp); });
      inp.addEventListener('input', function(){ inp.closest('.form-field').classList.remove('invalid'); });
    });
    form.addEventListener('submit', function(e){
      e.preventDefault();
      if (btn.disabled) return;
      var valid = true;
      $$('input[data-validate]', form).forEach(function(inp){ if (!validateField(inp)) valid = false; });
      if (!valid) return;
      btn.disabled = true; btn.classList.add('loading'); btn.textContent = lang === 'uk' ? 'Надсилаємо...' : 'Отправляем...';
      setTimeout(function(){
        form.classList.add('hidden');
        var success = $('.form-success', form.closest('.modal-dialog') || form.parentElement);
        if (success) success.classList.add('show');
      }, 1000);
    });
  });
}

/* ============ 10. REVEAL + COUNTERS ============ */
function initReveal(){
  var io = new IntersectionObserver(function(entries){
    entries.forEach(function(en){
      if (en.isIntersecting){ en.target.classList.add('visible'); io.unobserve(en.target); }
    });
  }, {threshold:.12});
  $$('.reveal').forEach(function(el, i){ el.style.transitionDelay = (i % 4) * 70 + 'ms'; io.observe(el); });
  var cio = new IntersectionObserver(function(entries){
    entries.forEach(function(en){
      if (!en.isIntersecting) return;
      var el = en.target, to = +el.dataset.counter, t0 = null;
      function tick(ts){ if (!t0) t0 = ts; var p = Math.min((ts - t0) / 900, 1); el.textContent = Math.round(to * (1 - Math.pow(1 - p, 3))); if (p < 1) requestAnimationFrame(tick); }
      requestAnimationFrame(tick);
      cio.unobserve(el);
    });
  }, {threshold:.6});
  $$('[data-counter]').forEach(function(el){ cio.observe(el); });
}

